#!/usr/bin/env node
// Palette toolkit for the frontend-design skill. Zero dependencies.
//
//   node palettes.mjs pick "build me a school website"   -> best-matching palettes + font pairing
//   node palettes.mjs css campus-evergreen               -> :root tokens (light + dark)
//   node palettes.mjs check                              -> WCAG contrast report for every palette
//   node palettes.mjs md > ../references/palettes.md     -> regenerate the reference doc

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { palettes } = JSON.parse(readFileSync(join(here, "../assets/palettes.json"), "utf8"));

// ---------- color math ----------
const hexToRgb = (h) => {
  const s = h.replace("#", "");
  const n = parseInt(s.length === 3 ? s.replace(/./g, "$&$&") : s, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const lum = (hex) => {
  const [r, g, b] = hexToRgb(hex).map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const contrast = (a, b) => {
  const [l1, l2] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
};

// pairs that must pass, with their minimum ratio
const RULES = [
  ["ink", "bg", 7, "body text"],
  ["ink", "surface", 7, "body text on cards"],
  ["muted", "bg", 4.5, "secondary text"],
  ["muted", "surface", 4.5, "secondary text on cards"],
  ["muted", "surface2", 4.5, "secondary text on alt sections"],
  ["onPrimary", "primary", 4.5, "button label"],
  ["onAccent", "accent", 4.5, "badge / accent button label"],
  ["primary", "bg", 3, "primary as UI/large text"],
];

function checkMode(tokens) {
  return RULES.map(([fg, bg, min, why]) => {
    const ratio = contrast(tokens[fg], tokens[bg]);
    return { fg, bg, min, why, ratio, ok: ratio >= min };
  });
}

// ---------- commands ----------
function pick(prompt) {
  const words = prompt.toLowerCase();
  const scored = palettes
    .map((p) => {
      let score = 0;
      for (const d of p.domains) if (words.includes(d)) score += d.split(" ").length * 3;
      for (const m of p.mood.split(/,\s*/)) if (words.includes(m)) score += 1;
      return { p, score };
    })
    .sort((a, b) => b.score - a.score);
  const top = scored.filter((s) => s.score > 0).slice(0, 3);
  if (!top.length) {
    console.log("No domain match. Pick by mood from `references/palettes.md`, or default to 'fresh-mint' (product) / 'editorial-mono' (content).");
    return;
  }
  for (const { p, score } of top) {
    console.log(`${p.id}  (score ${score})  — ${p.name}: ${p.mood}  | fonts: ${p.fonts}${p.prefer ? `  | prefers ${p.prefer}` : ""}`);
  }
  console.log(`\nNext: node ${process.argv[1].split("/").pop()} css ${top[0].p.id}`);
}

function css(id) {
  const p = palettes.find((x) => x.id === id);
  if (!p) throw new Error(`Unknown palette "${id}". Options: ${palettes.map((x) => x.id).join(", ")}`);
  const block = (t) => Object.entries(t).map(([k, v]) => `  --${kebab(k)}: ${v};`).join("\n");
  const first = p.prefer === "dark" ? "dark" : "light";
  const second = first === "dark" ? "light" : "dark";
  const extras = p.extras ? "\n" + block(p.extras) : "";
  console.log(`/* ${p.name} — ${p.mood}. Default scheme: ${first}. */
:root {
  color-scheme: ${first} ${second};
${block(p[first])}${extras}
}
@media (prefers-color-scheme: ${second}) {
  :root:not([data-theme="${first}"]) {
${block(p[second]).replace(/^/gm, "  ")}
  }
}
:root[data-theme="${second}"] {
${block(p[second])}
}`);
}
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

function check() {
  let failures = 0;
  for (const p of palettes) {
    for (const mode of ["light", "dark"]) {
      if (!p[mode]) continue;
      for (const r of checkMode(p[mode])) {
        if (!r.ok) {
          failures++;
          console.log(`FAIL ${p.id}/${mode}: ${r.fg} on ${r.bg} = ${r.ratio.toFixed(2)} (< ${r.min}, ${r.why})`);
        }
      }
    }
  }
  console.log(failures ? `\n${failures} contrast failure(s).` : `All ${palettes.length} palettes pass (light + dark, ${RULES.length} rules each).`);
  process.exitCode = failures ? 1 : 0;
}

function md() {
  const out = [];
  out.push(`# Palettes

<!-- GENERATED by scripts/palettes.mjs md — edit assets/palettes.json instead. -->

Every palette below is contrast-checked (WCAG AA minimum, body text ≥ 7:1) in **both light and dark**.
Pick by domain first, then by mood. Get ready-to-paste CSS with \`node scripts/palettes.mjs css <id>\`.

## Token roles

| Token | Use for |
|---|---|
| \`--bg\` | page background (never pure #FFF for warm brands — a tinted off-white feels designed) |
| \`--surface\` | cards, header, inputs |
| \`--surface2\` | alternating sections, wells, table stripes |
| \`--ink\` | body + heading text (never pure #000) |
| \`--muted\` | captions, meta, helper text |
| \`--border\` | hairlines, dividers, input borders |
| \`--primary\` / \`--on-primary\` | the ONE main action color + its label color |
| \`--accent\` / \`--on-accent\` | highlights, badges, a secondary CTA, underline marks — use sparingly (≤10% of the page) |

**60-30-10:** ~60% bg/surface, ~30% ink + surface2, ~10% primary+accent. If the page looks "colorful everywhere", you're over 10%.

## Quick map (domain → palette → fonts)

| Palette | Domains | Mood | Fonts |
|---|---|---|---|`);
  for (const p of palettes) {
    out.push(`| **${p.name}** \`${p.id}\` | ${p.domains.join(", ")} | ${p.mood} | \`${p.fonts}\` |`);
  }
  out.push("");
  for (const p of palettes) {
    out.push(`## ${p.name} — \`${p.id}\``);
    out.push(`*${p.mood}.* Domains: ${p.domains.join(", ")}. Fonts: \`${p.fonts}\`${p.prefer ? `. **Default to ${p.prefer} mode.**` : "."}`);
    out.push("");
    out.push("| Role | Light | Dark |");
    out.push("|---|---|---|");
    for (const k of Object.keys(p.light)) out.push(`| ${k} | \`${p.light[k]}\` | \`${p.dark[k]}\` |`);
    if (p.extras) out.push(`| extras | ${Object.entries(p.extras).map(([k, v]) => `${k} \`${v}\``).join(", ")} | |`);
    const worst = (m) => Math.min(...checkMode(p[m]).filter((r) => r.fg === "onPrimary").map((r) => r.ratio));
    out.push("");
    out.push(`Contrast: ink/bg ${contrast(p.light.ink, p.light.bg).toFixed(1)}:1 light, ${contrast(p.dark.ink, p.dark.bg).toFixed(1)}:1 dark · button label ${worst("light").toFixed(1)}:1 / ${worst("dark").toFixed(1)}:1`);
    out.push("");
  }
  out.push(`## Deriving a custom palette (when nothing fits)

1. Choose **one hue** for primary from the brand/domain (trust → blue/teal/green, warmth/food → red-orange/terracotta, luxury → near-black + one metal, kids → saturated violet/yellow, health → teal).
2. Tint the neutrals toward that hue: bg = primary hue at ~2–4% chroma, lightness 97–98%. Ink = same hue, lightness 12–18%.
3. Accent = complementary or split-complementary hue, used ≤10%.
4. In OKLCH: \`--primary: oklch(45% 0.12 H)\`, \`--bg: oklch(98% 0.01 H)\`, \`--ink: oklch(20% 0.03 H)\`, \`--muted: oklch(48% 0.03 H)\`, \`--accent: oklch(78% 0.15 H+150)\`.
5. Dark mode: don't invert. Lift primary to lightness 70–80%, keep bg at 8–12% with the same hue tint, ink at 92–95%.
6. Verify with the contrast rules above (add it to assets/palettes.json and run \`check\`).
`);
  console.log(out.join("\n"));
}

const [cmd, ...rest] = process.argv.slice(2);
if (cmd === "pick") pick(rest.join(" "));
else if (cmd === "css") css(rest[0]);
else if (cmd === "check") check();
else if (cmd === "md") md();
else console.log("usage: palettes.mjs pick <prompt> | css <id> | check | md");
